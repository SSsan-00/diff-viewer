#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";

const target = "wasm32-unknown-unknown";
const repoRoot = process.cwd();
const manifestPath = resolve(repoRoot, "rust", "diff-engine-wasm", "Cargo.toml");
const targetDir = resolve(repoRoot, ".wasm-target");
const wasmPath = resolve(
  targetDir,
  target,
  "release",
  "diff_engine_wasm.wasm",
);
const outputPath = resolve(repoRoot, "src", "diffEngine", "embeddedDiffWasm.ts");
const requireWasm = process.env.DIFF_VIEWER_REQUIRE_WASM === "1";

function getGitShortHead() {
  try {
    return execFileSync("git", ["rev-parse", "--short=12", "HEAD"], {
      cwd: repoRoot,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return "workspace";
  }
}

function resolveBuildId() {
  return process.env.DIFF_VIEWER_WASM_BUILD_ID?.trim() || getGitShortHead();
}

function hasInstalledTarget(name) {
  try {
    const output = execFileSync("rustup", ["target", "list", "--installed"], {
      cwd: repoRoot,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    });
    return output.split(/\r?\n/).some((line) => line.trim() === name);
  } catch {
    return null;
  }
}

function renderModule({ buildId, bytes, status }) {
  const buildIdLiteral = buildId ? JSON.stringify(buildId) : "null";
  const byteBody = bytes.length > 0 ? bytes.join(", ") : "";
  return `// Generated by scripts/generate-embedded-wasm.mjs
export const EMBEDDED_DIFF_WASM_BUILD_ID = ${buildIdLiteral};
export const EMBEDDED_DIFF_WASM_STATUS = ${JSON.stringify(status)};
export const EMBEDDED_DIFF_WASM_BYTES = new Uint8Array([${byteBody}]);
`;
}

function writeModule(payload) {
  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, payload);
}

function emitFallback(status) {
  writeModule(
    renderModule({
      buildId: null,
      bytes: [],
      status,
    }),
  );
  console.log(`[generate-embedded-wasm] ${status}`);
}

if (!existsSync(manifestPath)) {
  const status = "missing_manifest";
  if (requireWasm) {
    throw new Error(status);
  }
  emitFallback(status);
  process.exit(0);
}

const installedTarget = hasInstalledTarget(target);
if (installedTarget === false) {
  const status = "missing_target";
  if (requireWasm) {
    throw new Error(status);
  }
  emitFallback(status);
  process.exit(0);
}

const buildId = resolveBuildId();
mkdirSync(targetDir, { recursive: true });

try {
  execFileSync(
    "cargo",
    [
      "build",
      "--manifest-path",
      manifestPath,
      "--release",
      "--target",
      target,
      "--target-dir",
      targetDir,
    ],
    {
      cwd: repoRoot,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      env: {
        ...process.env,
        DIFF_VIEWER_WASM_BUILD_ID: buildId,
      },
    },
  );
  const wasm = readFileSync(wasmPath);
  const hash = createHash("sha256").update(wasm).digest("hex").slice(0, 16);
  const status = "metadata_only";
  writeModule(
    renderModule({
      buildId: `${buildId}-${hash}`,
      bytes: Array.from(wasm),
      status,
    }),
  );
  console.log(
    `[generate-embedded-wasm] ${status} ${relative(repoRoot, outputPath)} (${wasm.length} bytes).`,
  );
} catch (error) {
  const status = "build_failed";
  if (requireWasm) {
    throw error;
  }
  emitFallback(status);
}
